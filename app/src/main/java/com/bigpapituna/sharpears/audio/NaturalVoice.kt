package com.bigpapituna.sharpears.audio

import android.content.Context
import android.media.AudioAttributes
import android.media.AudioFormat
import android.media.AudioTrack
import android.media.MediaPlayer
import android.util.Log
import com.bigpapituna.sharpears.TAG
import com.bigpapituna.sharpears.engine.SpokenCatalog
import com.k2fsa.sherpa.onnx.OfflineTts
import com.k2fsa.sherpa.onnx.OfflineTtsConfig
import com.k2fsa.sherpa.onnx.OfflineTtsKokoroModelConfig
import com.k2fsa.sherpa.onnx.OfflineTtsModelConfig
import java.io.File
import java.util.concurrent.CountDownLatch
import java.util.concurrent.Executors
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicInteger

/**
 * The natural (Kokoro) voice, all on the phone. A line from [SpokenCatalog] plays its recording from
 * assets/voice; any other line is generated by the Kokoro model in files/kokoro (scripts/install-voice.ps1 puts
 * it there). Lines play one after another on a worker thread; [onIdle] runs (on that thread) when none are left.
 */
class NaturalVoice(private val context: Context, private val onIdle: () -> Unit) {
    private val worker = Executors.newSingleThreadExecutor { Thread(it, "natural-voice") }
    /** The recorded lines' file names: listing 3000 assets took about 100 ms of the first frame, so the worker reads it. */
    private val recorded: Set<String> by lazy { runCatching { context.assets.list("voice").orEmpty().toSet() }.getOrDefault(emptySet()) }
    /** The Kokoro speaker the recordings were made with (scripts/render_voice.py writes it), so both halves match. */
    private val speaker = runCatching { context.assets.open("voice/speaker.txt").reader().use { it.readText() }.trim().toInt() }.getOrDefault(3)
    private val modelDir = File(context.filesDir, "kokoro")
    private val attrs = AudioAttributes.Builder().setUsage(AudioAttributes.USAGE_ASSISTANCE_ACCESSIBILITY)
        .setContentType(AudioAttributes.CONTENT_TYPE_SPEECH).build()

    @Volatile private var generation = 0
    @Volatile private var playing: CountDownLatch? = null
    private val pending = AtomicInteger()
    /** Loaded once, on first use; [warmUp] starts it on its own thread so recorded lines never wait for it. */
    private val modelLoad = lazy { loadModel() }
    @Volatile private var modelFailed = false

    init { worker.execute { recorded.size } }

    val modelInstalled get() = File(modelDir, "model.int8.onnx").exists()
    val busy get() = pending.get() > 0

    private fun recording(text: String) = "${SpokenCatalog.key(text)}.ogg".takeIf { it in recorded }

    /** True when this voice can say [text]: it is recorded, or the model is on the phone. */
    fun canSay(text: String) = recording(text) != null || (modelInstalled && !modelFailed)

    /** Says [text] after what is queued ([flush]: instead of it); a generated line at [speed] (Kokoro's, 1 = normal). */
    fun say(text: String, flush: Boolean, speed: Float = 1f) {
        if (flush) stop()
        if (worker.isShutdown) { Log.d(TAG, "voice: released, dropped: $text"); return }   // a stale screen after a profile switch
        val gen = generation
        pending.incrementAndGet()
        worker.execute {
            try { if (gen == generation) speakNow(text, gen, speed) }
            catch (e: Exception) { Log.w(TAG, "voice: natural voice failed on \"$text\"", e) }
            finally { if (pending.decrementAndGet() == 0) onIdle() }
        }
    }

    /** Cuts off the line playing now and drops the ones waiting. */
    fun stop() { generation++; playing?.countDown() }

    /** Loads the model ahead of the first generated line (a second or two), without speaking. */
    fun warmUp() { if (modelInstalled) { warming = true; Thread({ modelLoad.value }, "natural-voice-load").start() } }
    /** [warmUp] started loading: [release] must wait for that model and free it (a profile switch mid-load leaked it). */
    @Volatile private var warming = false

    fun release() {
        stop()
        worker.execute { if (modelLoad.isInitialized() || warming) modelLoad.value?.release() }
        worker.shutdown()
    }

    private fun speakNow(text: String, gen: Int, speed: Float) {
        val file = recording(text)
        if (file != null) { Log.d(TAG, "voice: (recorded) $text"); playRecording(file, gen); return }
        val tts = modelLoad.value ?: return
        // Sentence by sentence: the first one plays while the next is made.
        val rate = tts.sampleRate()
        val track = AudioTrack.Builder().setAudioAttributes(attrs)
            .setAudioFormat(AudioFormat.Builder().setEncoding(AudioFormat.ENCODING_PCM_FLOAT).setSampleRate(rate)
                .setChannelMask(AudioFormat.CHANNEL_OUT_MONO).build())
            .setBufferSizeInBytes(rate * 4 * 30)      // 30 s, so writing never waits on playback
            .setTransferMode(AudioTrack.MODE_STREAM).build()
        try {
            val t0 = System.currentTimeMillis()
            var written = 0
            var playStart = 0L
            // An object, not a lambda: the native side looks up invoke(float[]): Integer by name, which a lambda lacks.
            tts.generateWithCallback(text, sid = speaker, speed = speed, callback = object : (FloatArray) -> Int {
                override fun invoke(chunk: FloatArray): Int {
                    if (gen != generation) return 0
                    if (written == 0) { Log.d(TAG, "voice: (first sound in ${System.currentTimeMillis() - t0} ms) $text"); track.play(); playStart = System.currentTimeMillis() }
                    track.write(chunk, 0, chunk.size, AudioTrack.WRITE_BLOCKING)
                    written += chunk.size
                    return 1
                }
            })
            // The head position can stall short of [written] once the track runs dry (the Fold7 did, 2026-10-22: Pup says
            // waited for this line for good), so the wait also ends when the audio's own length has passed.
            val deadline = playStart + written * 1000L / rate + 1500
            while (gen == generation && track.playbackHeadPosition < written && System.currentTimeMillis() < deadline) Thread.sleep(20)
            if (gen == generation && track.playbackHeadPosition < written) Log.d(TAG, "voice: ended by the clock, head ${track.playbackHeadPosition} of $written: $text")
        } finally { track.pause(); track.flush(); track.release() }
    }

    private fun playRecording(file: String, gen: Int) {
        val done = CountDownLatch(1)
        val mp = MediaPlayer()
        try {
            context.assets.openFd("voice/$file").use { mp.setDataSource(it.fileDescriptor, it.startOffset, it.length) }
            mp.setAudioAttributes(attrs)
            mp.setOnCompletionListener { done.countDown() }
            mp.setOnErrorListener { _, _, _ -> done.countDown(); true }
            mp.prepare()
            if (gen != generation) return
            playing = done
            mp.start()
            done.await(60, TimeUnit.SECONDS)
        } finally { playing = null; mp.release() }
    }

    private fun loadModel(): OfflineTts? {
        if (!modelInstalled) return null
        val d = modelDir.absolutePath
        val en = if (speaker in 20..27) "gb" else "us"     // Kokoro's British voices (bf_, bm_) read with the British lexicon
        val t0 = System.currentTimeMillis()
        val model = runCatching {
            OfflineTts(config = OfflineTtsConfig(model = OfflineTtsModelConfig(
                kokoro = OfflineTtsKokoroModelConfig(model = "$d/model.int8.onnx", voices = "$d/voices.bin", tokens = "$d/tokens.txt",
                    dataDir = "$d/espeak-ng-data", lexicon = "$d/lexicon-$en-en.txt", lang = "en-$en"),
                numThreads = 4)))
        }.onFailure { modelFailed = true; Log.w(TAG, "voice: the Kokoro model did not load", it) }.getOrNull()
        model?.let { Log.d(TAG, "voice: Kokoro loaded in ${System.currentTimeMillis() - t0} ms, speaker $speaker, ${it.sampleRate()} Hz") }
        return model
    }
}
