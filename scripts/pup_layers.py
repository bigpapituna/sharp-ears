"""The living pup's layers (2.10): SAM 2 cuts of nine poses into body, head, ears, tail and eyes.

Reads C:\\dev\\tools\\pup-parts\\pup_<pose>\\ (manifest.json and full-canvas RGBA PNGs, see that folder's README), crops each
layer to its alpha box (plus a pixel), writes it as lossy WebP q85 (alpha kept lossless) to
app/src/main/res/drawable-nodpi/pup_<pose>_<layer>.webp, and writes app/src/main/java/.../ui/pup/PupLayers.kt: each layer's
picture, its place on the pose's canvas, its pivot, its parent and the draw order, plus how far this pose's head, ears and
tail may turn (the cut's own limits, from the README's verdicts).
    python -I scripts/pup_layers.py [C:/dev/tools/pup-parts]
avatar_0 is cut too, but avatars are still pictures in the app, so it is left out.
"""
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable-nodpi"
OUT = ROOT / "app/src/main/java/com/bigpapituna/sharpears/ui/pup/PupLayers.kt"
PARTS = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("C:/dev/tools/pup-parts")

# pose -> (Pose entry, head max deg, ear max deg, tail max deg). Small heads where a paw touches the face (listening) or the
# neck pivot was placed by hand (sleeping); small ears where the tiny source shows background beside the cheeks (welcome);
# a small tail where it is a long sweep along the bottom (sleeping).
POSES = {
    "standing": ("STANDING", 12, 15, 20),
    "welcome": ("WELCOME", 12, 6, 20),
    "dancing": ("DANCING", 12, 12, 20),
    "listening": ("LISTENING", 4, 15, 20),
    "pointing": ("POINTING", 12, 15, 20),
    "head_tilt": ("HEAD_TILT", 12, 15, 20),
    "great_job": ("GREAT_JOB", 12, 15, 12),
    "sleeping": ("SLEEPING", 3, 6, 5),
    "wear_base": ("WEAR_BASE", 12, 15, 20),
}


def main():
    lines = []
    total = 0
    for pose, (entry, head_max, ear_max, tail_max) in POSES.items():
        d = PARTS / f"pup_{pose}"
        m = json.loads((d / "manifest.json").read_text())
        by = {l["name"]: l for l in m["layers"]}
        layers = []
        for name in m["draw_order"]:
            l = by[name]
            im = Image.open(d / l["file"]).convert("RGBA")
            box = im.getchannel("A").getbbox()
            x0, y0 = max(0, box[0] - 1), max(0, box[1] - 1)
            x1, y1 = min(im.width, box[2] + 1), min(im.height, box[3] + 1)
            res = f"pup_{pose}_{name}"
            path = RES / f"{res}.webp"
            im.crop((x0, y0, x1, y1)).save(path, "WEBP", quality=85, alpha_quality=100, method=6)
            total += path.stat().st_size
            parent = l.get("parent") or ""
            px, py = l["pivot"]
            layers.append(f'        PupLayer("{name}", R.drawable.{res}, {x0}f, {y0}f, {px}f, {py}f, "{parent}"),')
        lines.append(f"    Pose.{entry} to PupRig({m['canvas']['width']}, {m['canvas']['height']}, headMax = {head_max}f, earMax = {ear_max}f, "
                     f"tailMax = {tail_max}f, layers = listOf(")
        lines += layers
        lines.append("    )),")
    kt = "\n".join([
        "package com.bigpapituna.sharpears.ui.pup",
        "",
        "import com.bigpapituna.sharpears.R",
        "",
        "/*",
        " * Generated by scripts/pup_layers.py from C:\\dev\\tools\\pup-parts (SAM 2 cuts, see its README); do not edit by hand.",
        " * Each pose's layers in draw order: the picture (cropped to its alpha box), where its top left sits on the pose's",
        " * canvas, its pivot on that canvas, and its parent (a child turns with its parent, then about its own pivot).",
        " */",
        "internal val PUP_LAYERS: Map<Pose, PupRig> = mapOf(",
        *lines,
        ")",
        "",
    ])
    OUT.write_text(kt, encoding="utf-8")
    print(f"{len(POSES)} poses, {total} bytes of layers in {RES}")


if __name__ == "__main__":
    main()
